import type { DesignValidationIssue, NoteTypeTemplateDesign } from "./shared-schemas.js";
import {
  buildNoteTypeSearchQuery,
  escapeAnkiSearchLiteral,
} from "./note-type-schema-utils.js";

/** Creates a stale-write issue when the note-type design changed. */
export function createDesignRevisionIssue(
  expectedDesignHash: string | undefined,
  currentDesignHash: string,
): DesignValidationIssue | undefined {
  if (
    expectedDesignHash === undefined ||
    expectedDesignHash === currentDesignHash
  ) {
    return undefined;
  }

  return {
    severity: "error",
    code: "design_changed",
    path: "expectedDesignHash",
    message:
      "The note type design changed after it was read. Load it again before applying an update.",
  };
}

/** Returns an exact template by name, if it exists. */
export function findNoteTypeTemplate(
  templates: NoteTypeTemplateDesign[],
  templateName: string,
): NoteTypeTemplateDesign | undefined {
  return templates.find(({ name }) => name === templateName);
}

/** Checks template name uniqueness without allowing case-only ambiguity. */
export function hasNoteTypeTemplateName(
  templates: NoteTypeTemplateDesign[],
  templateName: string,
): boolean {
  const normalizedName = templateName.toLowerCase();
  return templates.some(
    ({ name }) => name.toLowerCase() === normalizedName,
  );
}

/** Returns templates with stable consecutive zero-based orders. */
export function normalizeTemplateOrders(
  templates: NoteTypeTemplateDesign[],
): NoteTypeTemplateDesign[] {
  return templates.map((template, order) => ({
    ...template,
    order,
  }));
}

/** Returns a copy with one template moved to a new zero-based order. */
export function repositionNoteTypeTemplates(
  templates: NoteTypeTemplateDesign[],
  templateName: string,
  newOrder: number,
): NoteTypeTemplateDesign[] {
  const currentOrder = templates.findIndex(
    ({ name }) => name === templateName,
  );

  if (currentOrder === -1) {
    return normalizeTemplateOrders(templates);
  }

  const reordered = templates.map((template) => ({ ...template }));
  const [template] = reordered.splice(currentOrder, 1);

  if (template === undefined) {
    return normalizeTemplateOrders(templates);
  }

  reordered.splice(newOrder, 0, template);
  return normalizeTemplateOrders(reordered);
}

/** Checks exact template order, names, and HTML. */
export function hasSameTemplateDesign(
  left: NoteTypeTemplateDesign[],
  right: NoteTypeTemplateDesign[],
): boolean {
  return (
    left.length === right.length &&
    left.every((template, index) => {
      const other = right[index];
      return (
        other !== undefined &&
        template.name === other.name &&
        template.order === other.order &&
        template.front === other.front &&
        template.back === other.back
      );
    })
  );
}

/** Builds an exact Anki search for cards generated by one template. */
export function buildTemplateCardsSearchQuery(
  modelName: string,
  templateName: string,
): string {
  return `${buildNoteTypeSearchQuery(modelName)} card:"${escapeAnkiSearchLiteral(templateName)}"`;
}

/** Builds a search for cards of the note type made by other templates. */
export function buildOtherTemplateCardsSearchQuery(
  modelName: string,
  templateName: string,
): string {
  return `${buildNoteTypeSearchQuery(modelName)} -card:"${escapeAnkiSearchLiteral(templateName)}"`;
}
